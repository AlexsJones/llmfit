const TABLES: Record<Lang, Record<string, string>> = { en: {}, de };

/** Drop the disambiguating context from a key: `'Height|bin'` -> `'Height'`. */
export function baseText(key: string) {
  const at = key.indexOf('|');
  return at === -1 ? key : key.slice(0, at);
}

function fill(text: string, vars?: Vars) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export function translate(lang: Lang, key: string, vars?: Vars) {
  return fill(TABLES[lang]?.[key] ?? baseText(key), vars);
}

/** Pick a starting language from the browser; anything unknown falls back to English. */
export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en';
  const tags = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of tags) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (LANGUAGES.some((l) => l.id === code)) return code as Lang;
  }
  return 'en';
}
